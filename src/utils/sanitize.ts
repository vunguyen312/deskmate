

const EMOJI_RE = new RegExp(
    [
        '[',
        '\\u{1F000}-\\u{1FAFF}', 

        '\\u{2600}-\\u{27BF}', 

        '\\u{2B00}-\\u{2BFF}', 

        '\\u{E0020}-\\u{E007F}', 

        '\\u{FE0F}\\u{200D}\\u{20E3}', 

        '\\u{1F3FB}-\\u{1F3FF}', 

        '\\u{00A9}\\u{00AE}\\u{2122}', 

        '\\u{203C}\\u{2049}\\u{2139}', 

        '\\u{2194}-\\u{21AA}', 

        '\\u{231A}-\\u{23FA}', 

        '\\u{25AA}-\\u{25FE}', 

        '\\u{2611}\\u{2614}\\u{2615}', 

        '\\u{2640}\\u{2642}', 

        '\\u{2660}-\\u{2667}', 

        '\\u{2693}-\\u{2764}', 

        '\\u{2795}-\\u{27BF}', 

        '\\u{2934}\\u{2935}', 

        '\\u{2B05}-\\u{2B07}', 

        '\\u{3030}\\u{303D}\\u{3297}\\u{3299}', 

        ']',
    ].join(''),
    'gu',
);

export function stripEmoji(text: string): string {
    return text.replace(EMOJI_RE, '');
}